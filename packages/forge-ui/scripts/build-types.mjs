// Bundles the package's types into one ambient declaration file for the built-in
// `forge:ui` module (shipped inside the forge binary and written to .forge/types/).
//
//   node packages/forge-ui/scripts/build-types.mjs [--check]
//
// Needs `typescript` and `@types/react`; it looks for them in examples/ui-showcase
// (run `npm ci` there first). `--check` fails if the committed file is out of date.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tools = resolve(root, "../../examples/ui-showcase/node_modules");
const tsc = join(tools, "typescript/bin/tsc");
if (!existsSync(tsc)) {
  console.error("typescript not found: run `npm ci --install-links` in examples/ui-showcase first");
  process.exit(2);
}
const out = join(mkdtempSync(join(tmpdir(), "forge-ui-types-")), "ui.d.ts");
execFileSync(process.execPath, [
  tsc, join(root, "src/index.ts"), "--declaration", "--emitDeclarationOnly", "--module", "amd",
  "--moduleResolution", "node10", "--jsx", "react-jsx", "--target", "ES2022", "--lib", "ES2022,DOM,DOM.Iterable",
  "--strict", "--skipLibCheck", "--typeRoots", join(tools, "@types"), "--types", "react,react-dom", "--outFile", out,
], { stdio: "inherit" });

// tsc names each source file's module after the file. Namespace the internal ones and
// make the index the public module.
let text = readFileSync(out, "utf8");
const names = [...text.matchAll(/^declare module "([^"]+)"/gm)].map((m) => m[1]);
for (const name of names) {
  const next = name === "index" ? "forge:ui" : `forge:ui/${name}`;
  text = text.replaceAll(`declare module "${name}"`, `declare module "${next}"`).replaceAll(`from "${name}"`, `from "${next}"`);
}
text = `// Types for the built-in \`forge:ui\` module. Generated by packages/forge-ui/scripts/build-types.mjs\n// from packages/forge-ui/src; do not edit by hand.\n${text}`;

const target = join(root, "forge-ui.d.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
    console.error("packages/forge-ui/forge-ui.d.ts is out of date: run node packages/forge-ui/scripts/build-types.mjs");
    process.exit(1);
  }
  console.log("forge-ui.d.ts is up to date");
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target} (${names.length} modules)`);
}
